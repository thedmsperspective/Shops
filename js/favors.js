/** A favor for a shop of this type that hasn't been used lately (used: the favors already handed out). */
export function favorFor(type, used = [], rand = Math.random) {
  const pool = [...(FAVORS[type] || []), ...FAVORS.any];
  const seen = new Set(used);
  let left = pool.filter(f => !seen.has(f));
  if (!left.length) left = pool; // every one has been used: start over
  return left[Math.floor(rand() * left.length)];
}
